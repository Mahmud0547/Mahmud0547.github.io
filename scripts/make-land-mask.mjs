// Builds lib/land-mask.ts: a 2° land/sea grid from Natural Earth 110m land (public domain), for the 3D globe demos.
// Run once: node scripts/make-land-mask.mjs (fetches world-atlas from jsDelivr).
import { writeFileSync } from "node:fs";

const topo = await (await fetch("https://cdn.jsdelivr.net/npm/world-atlas@2/land-110m.json")).json();
const { scale, translate } = topo.transform;
const arcs = topo.arcs.map((arc) => {
  let x = 0, y = 0;
  return arc.map(([dx, dy]) => { x += dx; y += dy; return [x * scale[0] + translate[0], y * scale[1] + translate[1]]; });
});
const ring = (ids) => ids.flatMap((i) => (i >= 0 ? arcs[i] : [...arcs[~i]].reverse()));
const polys = [];
for (const g of topo.objects.land.geometries) {
  const list = g.type === "Polygon" ? [g.arcs] : g.arcs;
  for (const p of list) polys.push(p.map(ring));
}
const inside = (x, y, r) => {
  let c = false;
  for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
    const [xi, yi] = r[i], [xj, yj] = r[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c;
  }
  return c;
};
const STEP = 2, W = 360 / STEP, H = 180 / STEP;
const bits = new Uint8Array(Math.ceil((W * H) / 8));
let land = 0;
for (let r = 0; r < H; r++) for (let c = 0; c < W; c++) {
  const lat = 90 - (r + 0.5) * STEP, lon = -180 + (c + 0.5) * STEP;
  if (polys.some((p) => inside(lon, lat, p[0]) && !p.slice(1).some((h) => inside(lon, lat, h)))) {
    const i = r * W + c; bits[i >> 3] |= 1 << (i & 7); land++;
  }
}
writeFileSync("lib/land-mask.ts", `// Generated by scripts/make-land-mask.mjs from Natural Earth 110m land (public domain). ${STEP}° grid, ${W}×${H}, row 0 = 90°N.
export const LAND = { step: ${STEP}, width: ${W}, height: ${H}, bits: "${Buffer.from(bits).toString("base64")}" };
`);
console.log("land cells", land, "of", W * H);
